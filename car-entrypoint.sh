#!/usr/bin/env bash
# Start Keystone (run-lab-supervisor.sh), telemetry, remote-ops, and Pilot (make run)
# in one network namespace. CAR_VIN is required.
set -euo pipefail

CAR_VIN="${CAR_VIN:?CAR_VIN is required}"
DBC_FAMILY="${DBC_FAMILY:-gai_EV}"
KEYSTONE_ROOT="/keystone"
PILOT_ROOT="/pilot"
IPC_PATH="${KEYSTONE_IPC_PATH:-/tmp/keystone.sock}"
KEYSTONE_BIN="${KEYSTONE_BIN:-/usr/local/bin/keystone}"

case "$DBC_FAMILY" in
  gai_EV|gai_ICE|prod_EV|prod_ICE) ;;
  *)
    echo "[car-entrypoint] unknown DBC_FAMILY=$DBC_FAMILY (want gai_EV|gai_ICE|prod_EV|prod_ICE)" >&2
    exit 2
    ;;
esac

TELE_ROOT="/apps/${DBC_FAMILY}/tele"
RO_ROOT="/apps/${DBC_FAMILY}/ro"

TELE_PID=""
RO_PID=""
PILOT_PID=""
KEYSTONE_PID=""
MQTT_PROXY_PID=""
STOPPING=0

# Autrio bootstrap currently returns mqtt_broker_host=localhost. On labnet that is
# empty; EMQX is on the host (reachable via LAB_GATEWAY / labshim). Forward only
# inside this car container — does not touch host Keystone or app source trees.
# If/when Autrio/Keystone advertise a lab-reachable broker (or honor an override),
# this localhost→gateway bridge can be removed.
LAB_GATEWAY="${LAB_GATEWAY:-10.74.0.1}"
LAB_MQTT_BROKER_PORT="${LAB_MQTT_BROKER_PORT:-1883}"

log() { echo "[car-entrypoint] $*"; }

if [[ ! -d "$TELE_ROOT" || ! -d "$RO_ROOT" ]]; then
  log "missing app trees for DBC_FAMILY=$DBC_FAMILY under /apps"
  exit 2
fi

log "VIN=$CAR_VIN apps=$DBC_FAMILY tele=$TELE_ROOT ro=$RO_ROOT"

write_app_json() {
  # Separate data_dir per app: tele and ro both flock data_dir/.lock; a shared
  # /var/lib/car makes remote-ops fail to start (nothing on :48311).
  local src="$1" dest="$2" data_dir="$3"
  python3 - "$src" "$dest" "$CAR_VIN" "$data_dir" <<'PY'
import json, pathlib, sys
src, dest, vin, data_dir = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
raw = json.loads(pathlib.Path(src).read_text())
raw["vin"] = vin
raw["data_dir"] = data_dir
pathlib.Path(data_dir).mkdir(parents=True, exist_ok=True)
pathlib.Path(dest).parent.mkdir(parents=True, exist_ok=True)
pathlib.Path(dest).write_text(json.dumps(raw, indent=2) + "\n")
PY
}

write_lab_supervisor_env() {
  local path="$KEYSTONE_ROOT/deploy/scripts/lab-supervisor.local.env"
  mkdir -p "$(dirname "$path")"
  : "${KEYSTONE_AUTRIO_URL:?KEYSTONE_AUTRIO_URL is required}"
  : "${KEYSTONE_TENANT_KEY:?KEYSTONE_TENANT_KEY is required}"
  : "${KEYSTONE_BIRTH_SECRET:?KEYSTONE_BIRTH_SECRET is required}"
  export KEYSTONE_BIN IPC_PATH CAR_VIN
  export KEYSTONE_AUTRIO_URL KEYSTONE_TENANT_KEY KEYSTONE_BIRTH_SECRET
  export KEYSTONE_KEYSTORE_BACKEND="${KEYSTONE_KEYSTORE_BACKEND:-file}"
  export KEYSTONE_IPC_PATH="$IPC_PATH"
  python3 - "$path" <<'PY'
import os, pathlib, sys

def sh_export(key: str, value: str) -> str:
    return "export %s=%s" % (key, repr(value))

path = pathlib.Path(sys.argv[1])
vals = [
    ("KEYSTONE_BIN", os.environ["KEYSTONE_BIN"]),
    ("KEYSTONE_AUTRIO_URL", os.environ["KEYSTONE_AUTRIO_URL"]),
    ("KEYSTONE_TENANT_KEY", os.environ["KEYSTONE_TENANT_KEY"]),
    ("KEYSTONE_VIN", os.environ["CAR_VIN"]),
    ("KEYSTONE_BIRTH_SECRET", os.environ["KEYSTONE_BIRTH_SECRET"]),
    ("KEYSTONE_SUPERVISOR", "1"),
    ("KEYSTONE_ALLOW_ENV_DESIRED", "1"),
    # Pilot is started by this entrypoint (make run), not as an OCI child.
    ("KEYSTONE_PILOT_RUNTIME", os.environ.get("KEYSTONE_PILOT_RUNTIME", "stub")),
    ("KEYSTONE_IPC_PATH", os.environ.get("KEYSTONE_IPC_PATH", "/tmp/keystone.sock")),
    ("KEYSTONE_CREDENTIAL_DIR", "/var/lib/keystone/creds"),
    ("KEYSTONE_STORAGE_ROOT", "/var/lib/keystone/storage"),
    ("KEYSTONE_KEYSTORE_BACKEND", os.environ.get("KEYSTONE_KEYSTORE_BACKEND", "file")),
    ("KEYSTONE_HOME", "/var/lib/keystone"),
]
lines = ["# Generated by car-entrypoint.sh — do not commit."]
lines.extend(sh_export(k, v) for k, v in vals)
path.write_text("\n".join(lines) + "\n")
PY
  chmod 600 "$path"
  log "wrote $path (VIN=$CAR_VIN ipc=$IPC_PATH)"
}

write_pilot_env() {
  local example="$PILOT_ROOT/.env.example"
  local dest="$PILOT_ROOT/.env"
  if [[ -f "$example" ]]; then
    cp "$example" "$dest"
  else
    : >"$dest"
  fi
  # Pilot loads .env with override=True — keep KEYSTONE_IPC_PATH in the file.
  if grep -q '^KEYSTONE_IPC_PATH=' "$dest" 2>/dev/null; then
    sed -i "s|^KEYSTONE_IPC_PATH=.*|KEYSTONE_IPC_PATH=${IPC_PATH}|" "$dest"
  else
    echo "KEYSTONE_IPC_PATH=${IPC_PATH}" >>"$dest"
  fi
  log "wrote $dest KEYSTONE_IPC_PATH=${IPC_PATH}"
}

wait_for_socket() {
  local path="$1" timeout="${2:-60}"
  local i=0
  while [[ "$i" -lt "$timeout" ]]; do
    if [[ -S "$path" ]]; then
      log "socket ready: $path"
      return 0
    fi
    if [[ -n "$KEYSTONE_PID" ]] && ! kill -0 "$KEYSTONE_PID" 2>/dev/null; then
      log "Keystone exited before creating $path"
      return 1
    fi
    sleep 1
    i=$((i + 1))
  done
  log "timeout waiting for $path"
  return 1
}

clear_stale_socket() {
  local path="$1"
  if [[ -e "$path" || -L "$path" ]]; then
    if [[ -S "$path" ]]; then
      # Something may still be listening; remove only if we own the restart.
      rm -f "$path" || true
      log "removed stale socket $path"
    else
      rm -rf "$path" || true
      log "removed stale path $path"
    fi
  fi
}

start_mqtt_localhost_forward() {
  # Why: Keystone applies Autrio connectivity.mqtt_broker_host after bootstrap.
  # Today that host is "localhost", so without this forward the car dies with
  # broker_unreachable before MQTT→Kafka→Crate. socat makes localhost:1883 in
  # this netns reach EMQX on the lab shim. Future: if Keystone connects only to
  # a non-localhost broker from bootstrap (or a real override), drop this helper.
  if ! command -v socat >/dev/null 2>&1; then
    log "socat missing — cannot forward MQTT localhost→${LAB_GATEWAY}:${LAB_MQTT_BROKER_PORT}"
    exit 2
  fi
  log "MQTT forward 127.0.0.1:${LAB_MQTT_BROKER_PORT} → ${LAB_GATEWAY}:${LAB_MQTT_BROKER_PORT}"
  socat \
    TCP-LISTEN:"${LAB_MQTT_BROKER_PORT}",bind=127.0.0.1,fork,reuseaddr \
    TCP:"${LAB_GATEWAY}:${LAB_MQTT_BROKER_PORT}" &
  MQTT_PROXY_PID=$!
}

start_keystone() {
  clear_stale_socket "$IPC_PATH"
  mkdir -p /var/lib/keystone/creds /var/lib/keystone/storage
  chmod 700 /var/lib/keystone/creds || true
  log "starting run-lab-supervisor.sh (KEYSTONE_BIN=$KEYSTONE_BIN)"
  # Background: script execs Keystone, so this PID becomes the daemon.
  "$KEYSTONE_ROOT/deploy/scripts/run-lab-supervisor.sh" run &
  KEYSTONE_PID=$!
  wait_for_socket "$IPC_PATH" 90
}

start_tele() {
  log "starting signal_telemetry vin=$CAR_VIN"
  (
    cd "$TELE_ROOT"
    exec python3 -m signal_telemetry --config "$TELE_ROOT/config/app.json"
  ) &
  TELE_PID=$!
}

start_ro() {
  log "starting remote_ops vin=$CAR_VIN"
  (
    cd "$RO_ROOT"
    exec python3 -m remote_ops --config "$RO_ROOT/config/app.json"
  ) &
  RO_PID=$!
}

start_pilot() {
  write_pilot_env
  mkdir -p /var/lib/pilot
  log "starting make -C $PILOT_ROOT run"
  (
    cd "$PILOT_ROOT"
    exec make run
  ) &
  PILOT_PID=$!
}

stop_all() {
  STOPPING=1
  log "stopping children"
  local pid
  for pid in "$PILOT_PID" "$RO_PID" "$TELE_PID" "$KEYSTONE_PID" "$MQTT_PROXY_PID"; do
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
      kill -TERM "$pid" 2>/dev/null || true
    fi
  done
  sleep 2
  for pid in "$PILOT_PID" "$RO_PID" "$TELE_PID" "$KEYSTONE_PID" "$MQTT_PROXY_PID"; do
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
      kill -KILL "$pid" 2>/dev/null || true
    fi
  done
}

trap stop_all TERM INT

mkdir -p /var/lib/car /var/lib/keystone /var/lib/pilot

# Config from shipped templates; VIN + per-app data_dir overridden for this container.
write_app_json "$TELE_ROOT/config/app.json" "$TELE_ROOT/config/app.json" "/var/lib/car/tele"
write_app_json "$RO_ROOT/config/app.json" "$RO_ROOT/config/app.json" "/var/lib/car/ro"
write_lab_supervisor_env

start_mqtt_localhost_forward
start_keystone
start_tele
start_ro
# Give HTTP listeners a moment before Pilot connects.
sleep 1
start_pilot

log "running: keystone=$KEYSTONE_PID tele=$TELE_PID ro=$RO_PID pilot=$PILOT_PID"

while true; do
  if [[ -n "$KEYSTONE_PID" ]] && ! kill -0 "$KEYSTONE_PID" 2>/dev/null; then
    log "Keystone exited — stopping container"
    stop_all
    exit 1
  fi
  if [[ -n "$TELE_PID" ]] && ! kill -0 "$TELE_PID" 2>/dev/null; then
    if [[ "$STOPPING" -eq 0 ]]; then
      log "telemetry exited — restarting"
      start_tele
    fi
  fi
  if [[ -n "$RO_PID" ]] && ! kill -0 "$RO_PID" 2>/dev/null; then
    if [[ "$STOPPING" -eq 0 ]]; then
      log "remote-ops exited — restarting"
      start_ro
    fi
  fi
  if [[ -n "$PILOT_PID" ]] && ! kill -0 "$PILOT_PID" 2>/dev/null; then
    if [[ "$STOPPING" -eq 0 ]]; then
      log "Pilot exited — restarting"
      start_pilot
    fi
  fi
  sleep 2
done
